"use client";

import { useEffect, useRef, useState } from "react";
import { useWorkspace } from "@/lib/workspace";
import type { MatchCandidate } from "@/lib/engine";
import { Badge } from "./ui";

export interface AssistantMessage {
  role: "user" | "assistant";
  lines: string[];
  source?: "bedrock" | "rules";
  model?: string;
}

const SUGGESTIONS = [
  "Why is the recommended plan cheapest?",
  "What pricing information is missing?",
  "Compare Northgate and Meridian",
  "Summarize my purchasing options",
];

export function useAssistant() {
  const { state, groups } = useWorkspace();
  return async (question: string, match?: MatchCandidate): Promise<AssistantMessage> => {
    const res = await fetch("/api/assistant", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        question,
        match,
        suppliers: state.suppliers,
        // Raw source cells are only needed for audit views, not for answering.
        items: state.items.map((i) => ({ ...i, raw: {} })),
        groups,
        basket: state.basket,
      }),
    });
    const json = await res.json();
    if (!res.ok) return { role: "assistant", lines: [json.error ?? "Something went wrong."], source: "rules" };
    return { role: "assistant", lines: json.lines, source: json.source, model: json.model };
  };
}

export function AnswerSource({ source, model }: { source?: "bedrock" | "rules"; model?: string }) {
  if (source === "bedrock")
    return (
      <Badge tone="ai" title={`Generated by Amazon Bedrock (${model}) from your workspace data. Verify before acting.`}>
        ✦ AI-generated · Bedrock
      </Badge>
    );
  return (
    <Badge tone="neutral" title="Deterministic answer computed from your workspace data. Bedrock is not configured in this environment.">
      = Rule-based answer
    </Badge>
  );
}

export function AssistantPanel({ open, onClose }: { open: boolean; onClose: () => void }) {
  const ask = useAssistant();
  const [messages, setMessages] = useState<AssistantMessage[]>([]);
  const [input, setInput] = useState("");
  const [busy, setBusy] = useState(false);
  const endRef = useRef<HTMLDivElement>(null);

  useEffect(() => endRef.current?.scrollIntoView({ behavior: "smooth" }), [messages]);
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open, onClose]);

  async function send(q: string) {
    if (!q.trim() || busy) return;
    setMessages((m) => [...m, { role: "user", lines: [q] }]);
    setInput("");
    setBusy(true);
    try {
      const a = await ask(q);
      setMessages((m) => [...m, a]);
    } catch {
      setMessages((m) => [...m, { role: "assistant", lines: ["Network error. Please try again."] }]);
    } finally {
      setBusy(false);
    }
  }

  if (!open) return null;
  return (
    <div className="fixed inset-0 z-50">
      <div className="absolute inset-0 bg-navy-950/30" onClick={onClose} />
      <aside role="dialog" aria-label="Procurement assistant" className="absolute inset-y-0 right-0 flex w-full max-w-md flex-col bg-white shadow-2xl">
        <div className="flex items-center justify-between border-b border-slate-200 px-5 py-4">
          <div>
            <p className="font-semibold text-navy-900">Procurement assistant</p>
            <p className="text-[12px] text-slate-500">Answers from your workspace data only</p>
          </div>
          <button type="button" onClick={onClose} aria-label="Close assistant" className="rounded-md p-1.5 text-slate-500 hover:bg-slate-100">
            <svg width="18" height="18" viewBox="0 0 20 20" aria-hidden>
              <path d="M5 5l10 10M15 5L5 15" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" />
            </svg>
          </button>
        </div>
        <div className="flex-1 space-y-4 overflow-y-auto px-5 py-5">
          {messages.length === 0 && (
            <div>
              <p className="text-sm text-slate-600">Ask about supplier differences, missing pricing, or your purchasing options.</p>
              <div className="mt-4 flex flex-col gap-2">
                {SUGGESTIONS.map((s) => (
                  <button key={s} type="button" onClick={() => send(s)} className="rounded-lg border border-slate-200 px-3 py-2 text-left text-[13px] text-navy-800 hover:bg-slate-50">
                    {s}
                  </button>
                ))}
              </div>
            </div>
          )}
          {messages.map((m, i) =>
            m.role === "user" ? (
              <div key={i} className="ml-8 rounded-lg bg-navy-900 px-3.5 py-2.5 text-sm text-white">
                {m.lines[0]}
              </div>
            ) : (
              <div key={i} className="mr-4 rounded-lg border border-slate-200 bg-slate-50 px-3.5 py-3">
                <div className="mb-2">
                  <AnswerSource source={m.source} model={m.model} />
                </div>
                <div className="space-y-1.5 text-[13px] leading-relaxed text-slate-700">
                  {m.lines.map((l, j) => (
                    <p key={j}>{l}</p>
                  ))}
                </div>
              </div>
            ),
          )}
          {busy && <p className="text-[13px] text-slate-400">Working…</p>}
          <div ref={endRef} />
        </div>
        <form
          className="flex gap-2 border-t border-slate-200 p-4"
          onSubmit={(e) => {
            e.preventDefault();
            send(input);
          }}
        >
          <input
            value={input}
            onChange={(e) => setInput(e.target.value)}
            placeholder="Ask about your suppliers…"
            aria-label="Question"
            className="h-10 flex-1 rounded-md border border-slate-300 px-3 text-sm"
          />
          <button type="submit" disabled={busy || !input.trim()} className="h-10 rounded-md bg-navy-900 px-4 text-sm font-medium text-white disabled:opacity-50">
            Ask
          </button>
        </form>
      </aside>
    </div>
  );
}
